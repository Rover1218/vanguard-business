// Writes install/ox_inventory_items.lua from shared/types.lua (for Qbox / ESX servers using ox_inventory).
// Usage: npm run ox-items
'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, createState, run } = require('./lua');

const L = createState();
run(L, 'Config = {}', 'config');
run(L, `dofile(ROOT .. '/shared/types.lua')`, 'types');

const body = run(L, `
    local function sorted(list)
        local ids = {}
        for id in pairs(list) do ids[#ids + 1] = id end
        table.sort(ids)
        return ids
    end

    local out = {}
    local function add(line) out[#out + 1] = line end

    add('    -- Vanguard Business ingredients')
    for _, id in ipairs(sorted(Ingredients)) do
        local item = Ingredients[id]
        add(("    ['%s'] = { label = '%s', weight = %d, stack = true, close = true, client = { image = '%s' } },")
            :format(id, item.label:gsub("'", "\\\\'"), item.weight, item.image))
    end

    add('')
    add('    -- Vanguard Business food and drink')
    for _, id in ipairs(sorted(Products)) do
        local item = Products[id]
        local anim = ConsumeAnims[item.kind]
        local status = {}
        if (item.hunger or 0) > 0 then status[#status + 1] = ('hunger = %d'):format(item.hunger * 10000) end
        if (item.thirst or 0) > 0 then status[#status + 1] = ('thirst = %d'):format(item.thirst * 10000) end
        add(("    ['%s'] = {"):format(id))
        add(("        label = '%s', weight = %d, stack = true, close = true,"):format(item.label:gsub("'", "\\\\'"), item.weight))
        add('        client = {')
        add(("            image = '%s',"):format(item.image))
        add(('            status = { %s },'):format(table.concat(status, ', ')))
        add(("            anim = { dict = '%s', clip = '%s' },"):format(anim.dict, anim.clip))
        add(("            prop = { model = \`%s\`, pos = vec3(0.02, 0.02, -0.02), rot = vec3(0.0, 0.0, 0.0) },"):format(ConsumeProps[item.prop]))
        add('            usetime = 5000,')
        add('        },')
        add('    },')
    end
    return table.concat(out, '\\n')`, 'generate');

const header = [
    '-- Vanguard Business items for ox_inventory (Qbox / ESX).',
    '-- Paste everything between the braces into ox_inventory/data/items.lua, inside its "return {" table,',
    '-- and copy vanguard-business/images/*.png into ox_inventory/web/images/.',
    '-- Generated by tools/gen-ox-items.js - edit shared/types.lua and run "npm run ox-items" instead of editing this file.',
    'return {',
];

const target = path.join(ROOT, 'install', 'ox_inventory_items.lua');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `${header.join('\n')}\n${body}\n}\n`);
console.log(`wrote ${path.relative(ROOT, target)}`);
