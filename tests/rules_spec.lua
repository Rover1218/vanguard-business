local T = require('tests.lib.t')
dofile(ROOT .. '/shared/rules.lua')

T.describe('Rules.wholeNumber', function()
    T.it('accepts whole numbers inside the range', function()
        T.eq(Rules.wholeNumber(5, 1, 10), 5)
        T.eq(Rules.wholeNumber(1, 1, 10), 1)
        T.eq(Rules.wholeNumber(10, 1, 10), 10)
        T.eq(Rules.wholeNumber(4.0, 1, 10), 4)
    end)
    T.it('rejects anything else', function()
        T.eq(Rules.wholeNumber(0, 1, 10), nil, 'below')
        T.eq(Rules.wholeNumber(11, 1, 10), nil, 'above')
        T.eq(Rules.wholeNumber(-3, 1, 10), nil, 'negative')
        T.eq(Rules.wholeNumber(2.5, 1, 10), nil, 'fraction')
        T.eq(Rules.wholeNumber('5', 1, 10), nil, 'string')
        T.eq(Rules.wholeNumber(0 / 0, 1, 10), nil, 'NaN')
        T.eq(Rules.wholeNumber(math.huge, 1, math.huge), nil, 'infinity')
        T.eq(Rules.wholeNumber(1e300, 1, 10), nil, 'huge')
        T.eq(Rules.wholeNumber(nil, 1, 10), nil, 'nil')
        T.eq(Rules.wholeNumber({}, 1, 10), nil, 'table')
    end)
end)

T.describe('Rules.cleanText', function()
    T.it('trims and keeps normal text', function()
        T.eq(Rules.cleanText('  Cat Café  ', 40), 'Cat Café')
    end)
    T.it('turns control characters into spaces', function()
        T.eq(Rules.cleanText('a\nb\tc', 40), 'a b c')
    end)
    T.it('cuts to the character limit without splitting a character', function()
        T.eq(Rules.cleanText('ééééé', 3), 'ééé')
        T.eq(Rules.cleanText('abcdef', 4), 'abcd')
    end)
    T.it('drops bytes that are not valid UTF-8', function()
        T.eq(Rules.cleanText('ab\255cd', 10), 'abcd')
    end)
    T.it('returns nil for empty or non-text input', function()
        T.eq(Rules.cleanText('   ', 10), nil)
        T.eq(Rules.cleanText(nil, 10), nil)
        T.eq(Rules.cleanText(42, 10), nil)
    end)
end)

T.describe('Rules.coords', function()
    T.it('accepts finite coordinates inside the map', function()
        T.eq(Rules.coords({ x = 1.5, y = -2, z = 30 }), { x = 1.5, y = -2.0, z = 30.0 })
    end)
    T.it('rejects missing, non-number, NaN and far-away values', function()
        T.eq(Rules.coords(nil), nil)
        T.eq(Rules.coords({ x = 1, y = 2 }), nil)
        T.eq(Rules.coords({ x = '1', y = 2, z = 3 }), nil)
        T.eq(Rules.coords({ x = 0 / 0, y = 2, z = 3 }), nil)
        T.eq(Rules.coords({ x = 1, y = 2, z = math.huge }), nil)
        T.eq(Rules.coords({ x = 99999, y = 2, z = 3 }), nil)
    end)
end)

T.describe('Rules.heading', function()
    T.it('wraps any finite number into 0-360', function()
        T.eq(Rules.heading(370), 10.0)
        T.eq(Rules.heading(-90), 270.0)
    end)
    T.it('rejects non-numbers', function()
        T.eq(Rules.heading('90'), nil)
