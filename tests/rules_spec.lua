    end)
end)

local PERMS = {
    [1] = { cook = true },
    [3] = { cook = true, hire = true },
}

T.describe('rank rules', function()
    T.it('can() reads the rank permission table', function()
        T.eq(Rules.can(PERMS, 1, 'cook'), true)
        T.eq(Rules.can(PERMS, 1, 'hire'), false)
        T.eq(Rules.can(PERMS, 2, 'cook'), false, 'rank without an entry')
        T.eq(Rules.can(PERMS, nil, 'cook'), false)
    end)
    T.it('canManage() needs a strictly higher rank', function()
        T.eq(Rules.canManage(3, 2), true)
        T.eq(Rules.canManage(3, 3), false)
        T.eq(Rules.canManage(2, 3), false)
        T.eq(Rules.canManage(nil, 1), false)
        T.eq(Rules.canManage(3, nil), false)
    end)
    T.it('canAssignRank() allows ranks below yours and never Owner', function()
        T.eq(Rules.canAssignRank(3, 1), true)
        T.eq(Rules.canAssignRank(3, 2), true)
        T.eq(Rules.canAssignRank(3, 3), false, 'own rank')
        T.eq(Rules.canAssignRank(4, 3), true)
        T.eq(Rules.canAssignRank(4, 4), false, 'owner')
        T.eq(Rules.canAssignRank(4, 0), false, 'zero')
        T.eq(Rules.canAssignRank(4, nil), false)
    end)
end)

T.describe('Rules.missingIngredients', function()
    local latte = { coffee_beans = 1, milk = 2 }
    T.it('is empty when there is enough for the quantity', function()
        T.eq(Rules.missingIngredients(latte, 2, { coffee_beans = 2, milk = 4 }), {})
    end)
    T.it('lists every short ingredient, sorted', function()
        T.eq(Rules.missingIngredients(latte, 3, { coffee_beans = 1 }), {
            { item = 'coffee_beans', need = 3, have = 1 },
            { item = 'milk', need = 6, have = 0 },
        })
    end)
end)

local CATALOG = {
    { item = 'milk', label = 'Milk', price = 20, pack = 10 },
    { item = 'ice', label = 'Ice', price = 10, pack = 20 },
}

T.describe('Rules.cartTotal', function()
    T.it('adds up a valid cart', function()
        local total, lines = Rules.cartTotal(CATALOG, { { item = 'milk', packs = 2 }, { item = 'ice', packs = 1 } }, 50)
        T.eq(total, 50)
        T.eq(lines, {
            { item = 'milk', packs = 2, amount = 20, cost = 40 },
            { item = 'ice', packs = 1, amount = 20, cost = 10 },
        })
    end)
    T.it('rejects empty, unknown, repeated and bad pack counts', function()
        T.eq(select(2, Rules.cartTotal(CATALOG, {}, 50)), 'The cart is empty')
        T.eq(select(2, Rules.cartTotal(CATALOG, nil, 50)), 'The cart is empty')
        T.eq(select(2, Rules.cartTotal(CATALOG, { { item = 'gold', packs = 1 } }, 50)), 'Unknown item in the cart')
        T.eq(select(2, Rules.cartTotal(CATALOG, { 'milk' }, 50)), 'Unknown item in the cart')
        T.eq(select(2, Rules.cartTotal(CATALOG, { { item = 'milk', packs = 1 }, { item = 'milk', packs = 1 } }, 50)), 'Milk is listed twice')
        T.eq(select(2, Rules.cartTotal(CATALOG, { { item = 'milk', packs = 0 } }, 50)), 'Pick 1-50 packs of Milk')
        T.eq(select(2, Rules.cartTotal(CATALOG, { { item = 'milk', packs = 51 } }, 50)), 'Pick 1-50 packs of Milk')
        T.eq(select(2, Rules.cartTotal(CATALOG, { { item = 'milk', packs = 1.5 } }, 50)), 'Pick 1-50 packs of Milk')
    end)
end)

