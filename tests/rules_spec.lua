T.describe('Rules.paycheckFor', function()
    local AMOUNTS = { [1] = 150, [2] = 250, [3] = 400, [4] = 600 }
    T.it('returns the amount for the rank', function()
        T.eq(Rules.paycheckFor(AMOUNTS, 1), 150)
        T.eq(Rules.paycheckFor(AMOUNTS, 4), 600)
    end)
    T.it('pays nothing for unknown ranks or bad config values', function()
        T.eq(Rules.paycheckFor(AMOUNTS, 5), 0)
        T.eq(Rules.paycheckFor(AMOUNTS, nil), 0)
        T.eq(Rules.paycheckFor({ [1] = -50 }, 1), 0, 'negative')
        T.eq(Rules.paycheckFor({ [1] = 99.5 }, 1), 0, 'fraction')
        T.eq(Rules.paycheckFor({ [1] = '100' }, 1), 0, 'string')
        T.eq(Rules.paycheckFor(nil, 1), 0, 'no table')
    end)
end)

